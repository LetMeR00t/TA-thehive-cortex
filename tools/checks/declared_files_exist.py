#!/usr/bin/env python3
"""Every file a .conf declares must actually exist in the package.

⚠️ **The defect lives in the gap between two files, so neither can shout on its
own.** `transforms.conf` declares `filename = thehive_datatypes.csv`; the
package has no `lookups/` directory at all. Nothing is wrong with either file
taken alone -- the declaration is well formed and the missing file is simply
absent -- and that is exactly why it survived: a dashboard doing
`| inputlookup thehive_datatypes.csv` fails on a fresh installation until an
alert action happens to create the file at runtime.

Same family as a scene pointing at a deleted entity, or a stanza whose target
was renamed: valid on both sides, broken in between.

    python tools/checks/declared_files_exist.py

Exit 0 when every declaration resolves, 1 otherwise, naming the declaration and
the path it expected.
"""

from __future__ import annotations

import configparser
import sys
from pathlib import Path

RACINE = Path(__file__).resolve().parents[2]
PAQUET = RACINE / "TA-thehive-cortex" / "package"
DEFAULT = PAQUET / "default"


def _lire(chemin: Path) -> configparser.ConfigParser:
    cp = configparser.ConfigParser(strict=False, interpolation=None)
    cp.read_string(chemin.read_text(encoding="utf-8"))
    return cp


def verifier_lookups() -> list[str]:
    """`filename =` in transforms.conf resolves inside the app's lookups/."""
    fichier = DEFAULT / "transforms.conf"
    if not fichier.is_file():
        return []
    manquants = []
    cp = _lire(fichier)
    for stanza in cp.sections():
        nom = cp[stanza].get("filename")
        if not nom:
            continue  # a kvstore lookup declares `collection`, not `filename`
        attendu = PAQUET / "lookups" / nom
        if not attendu.is_file():
            manquants.append(
                f"transforms.conf [{stanza}] declares filename = {nom}, "
                f"but package/lookups/{nom} does not exist"
            )
    return manquants


def verifier_collections() -> list[str]:
    """A kvstore lookup needs its collection declared in collections.conf."""
    transforms = DEFAULT / "transforms.conf"
    collections = DEFAULT / "collections.conf"
    if not transforms.is_file():
        return []
    connues = set(_lire(collections).sections()) if collections.is_file() else set()
    manquants = []
    cp = _lire(transforms)
    for stanza in cp.sections():
        if cp[stanza].get("external_type") != "kvstore":
            continue
        collection = cp[stanza].get("collection")
        if collection and collection not in connues:
            manquants.append(
                f"transforms.conf [{stanza}] uses collection = {collection}, "
                f"absent from collections.conf"
            )
    return manquants


def verifier_vues_de_nav() -> list[str]:
    """A nav entry pointing at a view this app does not ship.

    ⚠️ Deliberately tolerant: `search`, `alerts`, `dashboards` and friends are
    Splunk's own views, shipped by the platform, and flagging them would be the
    guard crying wolf on its very first run.
    """
    nav = DEFAULT / "data" / "ui" / "nav" / "default.xml"
    vues = DEFAULT / "data" / "ui" / "views"
    if not nav.is_file():
        return []
    import re
    fournies_par_splunk = {
        "search", "alerts", "dashboards", "reports", "datasets", "analytics_workspace",
    }
    # Generated by ucc-gen from globalConfig.json, so absent from the source tree.
    engendrees = {"configuration", "inputs", "dashboard"}
    presentes = {p.stem for p in vues.glob("*.xml")} if vues.is_dir() else set()

    # Names PROVEN not to be views: globalConfig.json declares them as TABS of
    # the configuration page. This is the only kind we fail on.
    import json
    onglets = set()
    gc = RACINE / "TA-thehive-cortex" / "globalConfig.json"
    if gc.is_file():
        d = json.loads(gc.read_text(encoding="utf-8"))
        for t in d.get("pages", {}).get("configuration", {}).get("tabs", []):
            if t.get("name"):
                onglets.add(t["name"])

    manquants, incertains = [], []
    for nom in re.findall(r'<view name="([^"]+)"', nav.read_text(encoding="utf-8")):
        if nom in presentes or nom in fournies_par_splunk or nom in engendrees:
            continue
        if nom in onglets:
            manquants.append(
                f"nav/default.xml points at view '{nom}', but globalConfig.json "
                f"declares it as a configuration TAB — a tab is not a view"
            )
        else:
            incertains.append(nom)

    # ⚠️ Reported, never fatal. Splunk ships views this repository cannot
    # enumerate, and failing on a name we cannot resolve would be the guard
    # crying wolf -- after which it gets switched off and protects nothing.
    for nom in incertains:
        print(f"  ⚠️  nav/default.xml points at view '{nom}': not shipped here. It may "
              f"be a Splunk built-in — verify on a real instance before removing it.")
    return manquants


def verifier_liens_de_notes() -> list[str]:
    """A relative link in the release notes must resolve inside the same tag.

    ⚠️ `release_notes/v4.0.0.md` was deleted in v4.2.0 while three release
    notes still linked to it with `./v4.0.0.md`. A relative link resolves in
    the CURRENT tag, so the file was 404 for everyone -- and those very
    instructions are labelled *mandatory*. Nothing in either file was wrong:
    the link was well formed and the deletion was deliberate.
    """
    dossier = RACINE / "release_notes"
    if not dossier.is_dir():
        return []
    import re
    manquants = []
    for note in sorted(dossier.glob("*.md")):
        texte = note.read_text(encoding="utf-8")
        for cible in re.findall(r"\]\((\./[^)]+)\)", texte):
            if not (dossier / cible[2:]).exists():
                manquants.append(
                    f"release_notes/{note.name} links to {cible}, which does not "
                    f"exist at this tag -- a relative link resolves here, not in "
                    f"the tag where the file still lived"
                )
    return manquants


def main() -> int:
    if not PAQUET.is_dir():
        print(f"package not found: {PAQUET}", file=sys.stderr)
        return 1

    constats = (
        verifier_lookups()
        + verifier_collections()
        + verifier_vues_de_nav()
        + verifier_liens_de_notes()
    )
    for c in constats:
        print(f"  {c}")

    if constats:
        print()
        print(f"{len(constats)} declaration(s) pointing at something that does not exist.")
        print("Both files are individually valid; the break is between them, which is")
        print("why nobody notices until a fresh installation fails.")
        return 1

    print("every declared file, collection, view and release-note link resolves.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
