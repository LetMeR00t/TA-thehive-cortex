#!/usr/bin/env python3
"""Every file a .conf declares must actually exist in the package.

⚠️ **The defect lives in the gap between two files, so neither can shout on its
own.** `transforms.conf` declares `filename = thehive_datatypes.csv`; the
package has no `lookups/` directory at all. Nothing is wrong with either file
taken alone -- the declaration is well formed and the missing file is simply
absent -- and that is exactly why it survived: a dashboard doing
`| inputlookup thehive_datatypes.csv` fails on a fresh installation until an
alert action happens to create the file at runtime.

Same family as a scene pointing at a deleted entity, or a stanza whose target
was renamed: valid on both sides, broken in between.

    python tools/checks/declared_files_exist.py

Exit 0 when every declaration resolves, 1 otherwise, naming the declaration and
the path it expected.
"""

from __future__ import annotations

import configparser
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PACKAGE = ROOT / "TA-thehive-cortex" / "package"
DEFAULT = PACKAGE / "default"


def _read_conf(path: Path) -> configparser.ConfigParser:
    cp = configparser.ConfigParser(strict=False, interpolation=None)
    # ⚠️ Splunk keys are case sensitive: `field.dataTypeList` is not
    # `field.datatypelist`. configparser lowercases option names by default,
    # which turned a correct declaration into a reported break.
    cp.optionxform = str
    cp.read_string(path.read_text(encoding="utf-8"))
    return cp


def check_lookups() -> list[str]:
    """`filename =` in transforms.conf resolves inside the app's lookups/."""
    conf_file = DEFAULT / "transforms.conf"
    if not conf_file.is_file():
        return []
    missing = []
    cp = _read_conf(conf_file)
    for stanza in cp.sections():
        name = cp[stanza].get("filename")
        if not name:
            continue  # a kvstore lookup declares `collection`, not `filename`
        expected = PACKAGE / "lookups" / name
        if not expected.is_file():
            missing.append(
                f"transforms.conf [{stanza}] declares filename = {name}, "
                f"but package/lookups/{name} does not exist"
            )
    return missing


def check_collections() -> list[str]:
    """A kvstore lookup needs its collection, and the fields it promises.

    ⚠️ Declaring the collection is not enough. `fields_list` is what a search
    gets back; a field named there and absent from `collections.conf` returns
    empty for every row -- a lookup that answers, with nothing in it. That
    failure is silent on both sides, which is the whole family this file
    exists for.
    """
    transforms = DEFAULT / "transforms.conf"
    collections = DEFAULT / "collections.conf"
    if not transforms.is_file():
        return []
    cp_collections = _read_conf(collections) if collections.is_file() else None
    known = set(cp_collections.sections()) if cp_collections else set()
    missing = []
    cp = _read_conf(transforms)
    for stanza in cp.sections():
        if cp[stanza].get("external_type") != "kvstore":
            continue
        collection = cp[stanza].get("collection")
        if not collection:
            missing.append(
                f"transforms.conf [{stanza}] is external_type = kvstore "
                f"but declares no collection"
            )
            continue
        if collection not in known:
            missing.append(
                f"transforms.conf [{stanza}] uses collection = {collection}, "
                f"absent from collections.conf"
            )
            continue
        # `_key` and `_user` are provided by the KV store itself, never declared.
        declared_fields = {
            key.split("field.", 1)[1]
            for key in cp_collections[collection]
            if key.startswith("field.")
        }
        for field in cp[stanza].get("fields_list", "").split(","):
            field = field.strip()
            if not field or field.startswith("_"):
                continue
            if field not in declared_fields:
                missing.append(
                    f"transforms.conf [{stanza}] promises the field '{field}' "
                    f"which collections.conf [{collection}] does not declare"
                )
    return missing


def check_nav_views() -> list[str]:
    """A nav entry pointing at a view this app does not ship.

    ⚠️ Deliberately tolerant: `search`, `alerts`, `dashboards` and friends are
    Splunk's own views, shipped by the platform, and flagging them would be the
    guard crying wolf on its very first run.
    """
    nav = DEFAULT / "data" / "ui" / "nav" / "default.xml"
    views = DEFAULT / "data" / "ui" / "views"
    if not nav.is_file():
        return []
    import re
    provided_by_splunk = {
        "search", "alerts", "dashboards", "reports", "datasets", "analytics_workspace",
    }
    # Generated by ucc-gen from globalConfig.json, so absent from the source tree.
    generated = {"configuration", "inputs", "dashboard"}
    present = {p.stem for p in views.glob("*.xml")} if views.is_dir() else set()

    # Names PROVEN not to be views: globalConfig.json declares them as TABS of
    # the configuration page. This is the only kind we fail on.
    import json
    tabs = set()
    gc = ROOT / "TA-thehive-cortex" / "globalConfig.json"
    if gc.is_file():
        d = json.loads(gc.read_text(encoding="utf-8"))
        for t in d.get("pages", {}).get("configuration", {}).get("tabs", []):
            if t.get("name"):
                tabs.add(t["name"])

    missing, uncertain = [], []
    for name in re.findall(r'<view name="([^"]+)"', nav.read_text(encoding="utf-8")):
        if name in present or name in provided_by_splunk or name in generated:
            continue
        if name in tabs:
            missing.append(
                f"nav/default.xml points at view '{name}', but globalConfig.json "
                f"declares it as a configuration TAB — a tab is not a view"
            )
        else:
            uncertain.append(name)

    # ⚠️ Reported, never fatal. Splunk ships views this repository cannot
    # enumerate, and failing on a name we cannot resolve would be the guard
    # crying wolf -- after which it gets switched off and protects nothing.
    for name in uncertain:
        print(f"  ⚠️  nav/default.xml points at view '{name}': not shipped here. It may "
              f"be a Splunk built-in — verify on a real instance before removing it.")
    return missing


def check_note_links() -> list[str]:
    """A relative link in the release notes must resolve inside the same tag.

    ⚠️ `release_notes/v4.0.0.md` was deleted in v4.2.0 while three release
    notes still linked to it with `./v4.0.0.md`. A relative link resolves in
    the CURRENT tag, so the file was 404 for everyone -- and those very
    instructions are labelled *mandatory*. Nothing in either file was wrong:
    the link was well formed and the deletion was deliberate.
    """
    folder = ROOT / "release_notes"
    if not folder.is_dir():
        return []
    import re
    missing = []
    for note in sorted(folder.glob("*.md")):
        text = note.read_text(encoding="utf-8")
        for target in re.findall(r"\]\((\./[^)]+)\)", text):
            if not (folder / target[2:]).exists():
                missing.append(
                    f"release_notes/{note.name} links to {target}, which does not "
                    f"exist at this tag -- a relative link resolves here, not in "
                    f"the tag where the file still lived"
                )
    return missing


def main() -> int:
    if not PACKAGE.is_dir():
        print(f"package not found: {PACKAGE}", file=sys.stderr)
        return 1

    findings = (
        check_lookups()
        + check_collections()
        + check_nav_views()
        + check_note_links()
    )
    for c in findings:
        print(f"  {c}")

    if findings:
        print()
        print(f"{len(findings)} declaration(s) pointing at something that does not exist.")
        print("Both files are individually valid; the break is between them, which is")
        print("why nobody notices until a fresh installation fails.")
        return 1

    print("every declared file, collection, view and release-note link resolves.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
