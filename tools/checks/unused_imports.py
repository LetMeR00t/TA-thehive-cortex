#!/usr/bin/env python3
"""An import that is never used, minus the ones that exist FOR their side effect.

⚠️ The subtlety that makes this check worth writing carefully: **a side-effect
import is never unused, and it looks exactly like an unused one.**

`ta_thehive_cortex_declare` and `import_declare_test` put the add-on's
directories on `sys.path`. Nothing references their name -- that is the whole
point -- so a naive sweep deletes them and breaks every module that touches a
vendored library. Measured: the first version of this very check reported both,
and removing them would have turned a fragile module into a broken one.

Files generated by `ucc-gen` (`*_rh_*.py`) and vendored scaffolding
(`cim_actions.py`, `alert_actions_base.py`, `modinput_wrapper/`) are skipped:
they are not ours to tidy, and cleaning them creates a diff that comes back at
the next build.

    python tools/checks/unused_imports.py

Exit 0 when nothing is imported for nothing.
"""

from __future__ import annotations

import ast
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BIN = ROOT / "TA-thehive-cortex" / "package" / "bin"

#: ⚠️ Imported for what they DO, not for what they name.
SIDE_EFFECTS = {"ta_thehive_cortex_declare", "import_declare_test"}

#: Not ours: generated by ucc-gen, or vendored scaffolding.
NOT_OURS = {"cim_actions.py", "alert_actions_base.py"}
IGNORED_DIRS = {"libs", "__pycache__", "modinput_wrapper"}


def modules():
    for path in sorted(BIN.rglob("*.py")):
        if any(p in IGNORED_DIRS for p in path.parts):
            continue
        if path.name in NOT_OURS or "_rh_" in path.name:
            continue
        yield path


def unused(path: Path) -> list[tuple[int, str]]:
    source = path.read_text(encoding="utf-8")
    try:
        tree = ast.parse(source)
    except SyntaxError:
        return []

    # The body WITHOUT the import lines: a name that appears only in an
    # import is used nowhere.
    body = "\n".join(
        l for l in source.splitlines() if not l.lstrip().startswith(("import ", "from "))
    )

    found = []
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            pairs = [(al.asname or al.name.split(".")[0], al.name) for al in node.names]
        elif isinstance(node, ast.ImportFrom):
            if node.module == "__future__":
                continue
            pairs = [(al.asname or al.name, al.name) for al in node.names if al.name != "*"]
        else:
            continue
        for name, full in pairs:
            if name in SIDE_EFFECTS or full in SIDE_EFFECTS:
                continue
            if not re.search(rf"\b{re.escape(name)}\b", body):
                found.append((node.lineno, name))
    return found


def main() -> int:
    total = 0
    for path in modules():
        for line, name in unused(path):
            print(f"  {path.relative_to(ROOT)}:{line}  `{name}` imported and never used")
            total += 1

    if total:
        print()
        print(f"{total} import(s) for nothing. ⚠️ Before deleting one, ask what it")
        print("DOES: an import that sets up sys.path names nothing on purpose.")
        return 1

    print("no import is there for nothing.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
