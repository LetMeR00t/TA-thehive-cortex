#!/usr/bin/env python3
"""An import that is never used, minus the ones that exist FOR their side effect.

⚠️ The subtlety that makes this check worth writing carefully: **a side-effect
import is never unused, and it looks exactly like an unused one.**

`ta_thehive_cortex_declare` and `import_declare_test` put the add-on's
directories on `sys.path`. Nothing references their name -- that is the whole
point -- so a naive sweep deletes them and breaks every module that touches a
vendored library. Measured: the first version of this very check reported both,
and removing them would have turned a fragile module into a broken one.

Files generated by `ucc-gen` (`*_rh_*.py`) and vendored scaffolding
(`cim_actions.py`, `alert_actions_base.py`, `modinput_wrapper/`) are skipped:
they are not ours to tidy, and cleaning them creates a diff that comes back at
the next build.

    python tools/checks/unused_imports.py

Exit 0 when nothing is imported for nothing.
"""

from __future__ import annotations

import ast
import re
import sys
from pathlib import Path

RACINE = Path(__file__).resolve().parents[2]
BIN = RACINE / "TA-thehive-cortex" / "package" / "bin"

#: ⚠️ Imported for what they DO, not for what they name.
EFFETS_DE_BORD = {"ta_thehive_cortex_declare", "import_declare_test"}

#: Not ours: generated by ucc-gen, or vendored scaffolding.
NON_A_NOUS = {"cim_actions.py", "alert_actions_base.py"}
DOSSIERS_IGNORES = {"libs", "__pycache__", "modinput_wrapper"}


def modules():
    for chemin in sorted(BIN.rglob("*.py")):
        if any(p in DOSSIERS_IGNORES for p in chemin.parts):
            continue
        if chemin.name in NON_A_NOUS or "_rh_" in chemin.name:
            continue
        yield chemin


def inutilises(chemin: Path) -> list[tuple[int, str]]:
    source = chemin.read_text(encoding="utf-8")
    try:
        arbre = ast.parse(source)
    except SyntaxError:
        return []

    # Le corps SANS les lignes d'import : un nom qui n'apparaît que dans un
    # import n'est utilisé nulle part.
    corps = "\n".join(
        l for l in source.splitlines() if not l.lstrip().startswith(("import ", "from "))
    )

    trouves = []
    for noeud in ast.walk(arbre):
        if isinstance(noeud, ast.Import):
            paires = [(al.asname or al.name.split(".")[0], al.name) for al in noeud.names]
        elif isinstance(noeud, ast.ImportFrom):
            if noeud.module == "__future__":
                continue
            paires = [(al.asname or al.name, al.name) for al in noeud.names if al.name != "*"]
        else:
            continue
        for nom, complet in paires:
            if nom in EFFETS_DE_BORD or complet in EFFETS_DE_BORD:
                continue
            if not re.search(rf"\b{re.escape(nom)}\b", corps):
                trouves.append((noeud.lineno, nom))
    return trouves


def main() -> int:
    total = 0
    for chemin in modules():
        for ligne, nom in inutilises(chemin):
            print(f"  {chemin.relative_to(RACINE)}:{ligne}  `{nom}` imported and never used")
            total += 1

    if total:
        print()
        print(f"{total} import(s) for nothing. ⚠️ Before deleting one, ask what it")
        print("DOES: an import that sets up sys.path names nothing on purpose.")
        return 1

    print("no import is there for nothing.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
