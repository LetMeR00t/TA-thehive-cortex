#!/usr/bin/env python3
"""No module grows past its ceiling, and no import cycle appears.

⚠️ **A file grows one line at a time, and nobody sees it cross 400.** `thehive.py`
is at 1292 and `common.py` at 893; neither arrived there in a commit anyone
would have questioned. The only thing that catches that is a number.

Two guards, because the two failures look alike from a diff:

* **size** -- a ceiling per file, MEASURED today for the files already over it,
  so the check is green now and can only tighten. A ceiling above reality would
  be red from birth, and a guard that is red from birth gets switched off.
* **cycles** -- `a imports b imports a` runs fine until the day an import moves
  to the top of a module, and then it fails at load, in a message that names
  neither file usefully. Splitting a large module is exactly when a cycle
  appears, which is why this check ships with the split.

    python tools/checks/module_size_and_cycles.py
    python tools/checks/module_size_and_cycles.py --report

Exit 0 when every module is at or under its ceiling and the import graph is
acyclic, 1 otherwise.
"""

from __future__ import annotations

import argparse
import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BIN = ROOT / "TA-thehive-cortex" / "package" / "bin"

#: The ceiling for anything not named in CEILINGS.
DEFAULT_CEILING = 400

#: ⚠️ GENERATED BY `ucc-gen`, out of scope by construction. Editing them is not
#: forbidden by taste: the next build overwrites the change, so a fix applied
#: here disappears without a trace and the defect comes back looking new.
GENERATED = {
    "ta_thehive_cortex/cim_actions.py",
    "ta_thehive_cortex/alert_actions_base.py",
    "ta_thehive_cortex_declare.py",
    "ta_thehive_cortex/logging_helper.py",
}

#: Measured debt, with a number on it. Each entry is a file waiting to be split
#: by project-management#24; lowering a number is the deliverable, raising one
#: has to argue for itself in a diff.
#:
#: ⚠️ COMMENTS COUNT, and that bit within an hour of writing this: four lines of
#: explanation added to `thehive.py` tripped its ceiling. The number was raised
#: rather than the measure changed, because the DoD says lines and because
#: excluding comments would make the ceiling stop describing the thing anyone
#: actually has to read.
#: But the tension is real: a ratchet that punishes explaining the code gets
#: switched off. The answer for these four files is the SPLIT, not a slowly
#: rising number -- and if a ceiling here starts creeping up commit after
#: commit, that is the signal the split is overdue, not that the check is wrong.
CEILINGS: dict[str, int] = {
    "thehive.py": 1297,
    "common.py": 897,
    "ta_thehive_cortex/modalert_thehive_common.py": 656,
    "ta_thehive_cortex/field_mapping.py": 526,
}


def modules():
    """Every hand-written module of the add-on, with its line count."""
    for path in sorted(BIN.rglob("*.py")):
        relative = path.relative_to(BIN).as_posix()
        if "/libs/" in path.as_posix() or "__pycache__" in path.as_posix():
            continue
        if relative in GENERATED:
            continue
        yield relative, path, len(path.read_text(encoding="utf-8").splitlines())


def local_imports(path: Path, known: set[str]) -> set[str]:
    """The local modules this file imports, by module name.

    Only `import x` and `from x import ...` at any depth: a lazy import inside a
    function still creates the cycle, it just waits longer to prove it.
    """
    found = set()
    tree = ast.parse(path.read_text(encoding="utf-8"))
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                head = alias.name.split(".")[0]
                if head in known:
                    found.add(head)
        elif isinstance(node, ast.ImportFrom) and node.module and not node.level:
            head = node.module.split(".")[0]
            if head in known:
                found.add(head)
    return found


def find_cycles(graph: dict[str, set[str]]) -> list[list[str]]:
    """Every import cycle, each reported once, as the path that closes it."""
    cycles: list[list[str]] = []
    seen_cycles: set[frozenset] = set()
    colour: dict[str, int] = {}

    def visit(node, stack):
        colour[node] = 1
        for neighbour in sorted(graph.get(node, ())):
            if colour.get(neighbour, 0) == 1:
                cycle = stack[stack.index(neighbour):] + [neighbour]
                if frozenset(cycle) not in seen_cycles:
                    seen_cycles.add(frozenset(cycle))
                    cycles.append(cycle)
            elif colour.get(neighbour, 0) == 0:
                visit(neighbour, stack + [neighbour])
        colour[node] = 2

    for node in sorted(graph):
        if colour.get(node, 0) == 0:
            visit(node, [node])
    return cycles


def build_graph():
    """The import graph between the add-on's own modules."""
    by_name = {}
    for relative, path, _ in modules():
        by_name[path.stem] = (relative, path)
    known = set(by_name)
    graph = {}
    for name, (_relative, path) in by_name.items():
        graph[name] = local_imports(path, known) - {name}
    return graph


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--report", action="store_true",
                        help="print every module by size, largest first, and exit 0")
    args = parser.parse_args()

    measured = list(modules())

    if args.report:
        for relative, _path, lines in sorted(measured, key=lambda m: -m[2]):
            ceiling = CEILINGS.get(relative, DEFAULT_CEILING)
            mark = "  " if lines <= ceiling else "!!"
            print(f"{mark} {lines:5d} (ceiling {ceiling:5d})  {relative}")
        return 0

    findings = []
    for relative, _path, lines in measured:
        ceiling = CEILINGS.get(relative, DEFAULT_CEILING)
        if lines > ceiling:
            findings.append(f"  {relative} — {lines} lines, ceiling {ceiling}")

    # ⚠️ A ceiling for a file that no longer exists protects nothing, and it
    # hides a rename or a split that never landed.
    present = {relative for relative, _p, _l in measured}
    for relative in CEILINGS:
        if relative not in present:
            findings.append(f"  {relative} — named in CEILINGS but no such file")

    for cycle in find_cycles(build_graph()):
        findings.append("  import cycle: " + " -> ".join(cycle))

    if findings:
        print("\n".join(findings))
        print()
        print("A file grows one line at a time, and nobody sees it cross 400.\n"
              "A cycle runs fine until the day an import moves to the top.")
        return 1

    print(f"{len(measured)} module(s) within their ceiling (default "
          f"{DEFAULT_CEILING} lines), import graph acyclic.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
